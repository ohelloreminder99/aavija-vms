#!/usr/bin/env node
/**
 * AAVIJA VMS — Rebuild Master SQL
 * ──────────────────────────────────────────────────────────────────────────────
 * Concatenates all migration files (in chronological order) with the base setup
 * and writes a fresh MASTER_DB_SETUP.sql.
 *
 * Run:  node scripts/rebuild-master-sql.js
 *
 * When to run:
 *   - After adding any new file to supabase/migrations/
 *   - Before deploying to a new country
 *   - After any schema change
 */

const fs   = require('fs');
const path = require('path');

const ROOT        = path.resolve(__dirname, '..');
const MIGRATIONS  = path.join(ROOT, 'supabase', 'migrations');
const BACKUPS     = path.join(ROOT, 'database_sql_backups');
const OUTPUT      = path.join(BACKUPS, 'MASTER_DB_SETUP.sql');
const CONSOLIDATED = path.join(BACKUPS, 'CONSOLIDATED_FINAL_SETUP.sql');

// ── Collect migration files ────────────────────────────────────────────────────

const migrationFiles = fs
  .readdirSync(MIGRATIONS)
  .filter(f => f.endsWith('.sql'))
  .sort(); // chronological by filename prefix (YYYYMMDD_*)

console.log(`\n🔍 Found ${migrationFiles.length} migration files in supabase/migrations/:`);
migrationFiles.forEach(f => console.log(`   ✓ ${f}`));

// ── Build header ───────────────────────────────────────────────────────────────

const now    = new Date().toISOString();
const header = `-- ============================================================
-- AAVIJA VMS — MASTER DATABASE SETUP
-- Auto-generated by: node scripts/rebuild-master-sql.js
-- Generated at:      ${now}
-- DO NOT EDIT MANUALLY — run rebuild-master-sql.js instead
-- ============================================================
--
-- HOW TO USE:
--   1. Create a new Supabase project
--   2. Enable extensions: pgcrypto, uuid-ossp, pg_cron
--   3. Paste this entire file in the SQL Editor and Run
--   4. Follow NEW_COUNTRY_SETUP.md for remaining config steps
-- ============================================================

`;

// ── Read base file if it exists ────────────────────────────────────────────────

let baseContent = '';
if (fs.existsSync(CONSOLIDATED)) {
  baseContent = `
-- ============================================================
-- BASE SETUP (from CONSOLIDATED_FINAL_SETUP.sql)
-- ============================================================

` + fs.readFileSync(CONSOLIDATED, 'utf8') + '\n\n';
  console.log(`\n📄 Using base: CONSOLIDATED_FINAL_SETUP.sql`);
}

// ── Read and append migrations ─────────────────────────────────────────────────

let migrationsContent = '';
for (const file of migrationFiles) {
  const filePath = path.join(MIGRATIONS, file);
  const content  = fs.readFileSync(filePath, 'utf8');
  migrationsContent += `
-- ============================================================
-- MIGRATION: ${file}
-- ============================================================

${content}

`;
}

// ── Write output ───────────────────────────────────────────────────────────────

const fullContent = header + baseContent + migrationsContent;
fs.writeFileSync(OUTPUT, fullContent, 'utf8');

const lines  = fullContent.split('\n').length;
const sizeKb = Math.round(fs.statSync(OUTPUT).size / 1024);

console.log(`\n✅ MASTER_DB_SETUP.sql rebuilt successfully!`);
console.log(`   📍 Output: database_sql_backups/MASTER_DB_SETUP.sql`);
console.log(`   📊 ${lines} lines, ${sizeKb} KB`);
console.log(`   📦 Includes: 1 base + ${migrationFiles.length} migrations\n`);
